// مفاتيح آمنة في قاعدة البيانات لنصوص يكتبها الناس: اسم اللاعب 2 في اللعب المحلي، ومعرّف خصم من بيانات الغرفة.
// Firebase يرفض في المفتاح . # $ [ ] ومحارف التحكم — فيفشل الحفظ كله (كانت المباراة لا تُسجَّل أبداً: لا سجل ولا
// إحصائيات ولا خبرة)، و"/" يقسم المسار — فتُحفظ في مكان لا تقرؤه نافذة الإحصائيات (فحص 1 لـv36.0: <b>تجربة</b>).
// نرمّز هذه وحدها: الأسماء العادية (وفيها %) تبقى بمفاتيحها القديمة فلا تضيع إحصائياتها، والاسم نفسه يُحفظ كما كُتب
// في حقل name للعرض. كل رمز ممنوع ← "%" وحرفان كبيران (A..P لكل نصف بايت: "." ← %CO، "/" ← %CP، "#" ← %CD) —
// والاسم يُصغَّر قبل الترميز فلا يحوي حرفاً كبيراً، فلا يصنع نصٌّ مكتوب رمزاً كهذا: اسمان مختلفان لا يتشاركان مفتاحاً
// (بترميز %23 المعتاد كان "Player#1" و"Player%231" مفتاحاً واحداً).
const FORBIDDEN = /[.#$\[\]\/\u0000-\u001F\u007F]/g;
const enc = ch => { const c = ch.charCodeAt(0); return '%' + String.fromCharCode(65 + (c >> 4), 65 + (c & 15)); };

/** مفتاح إحصائيات المحلي لاسم اللاعب 2 — كما كان (حروف صغيرة، والمسافات _) مع ترميز الممنوع */
export function localStatsKey(name) {
  const n = String(name ?? '').trim().toLowerCase().replace(/\s+/g, '_');
  return n ? 'vs_' + n.replace(FORBIDDEN, enc) : '__general__';
}

/** يصلح مفتاحاً كما هو؟ (معرّفات الحسابات: حروف وأرقام و_ و- فقط) — لمعرّف يأتي من بيانات يكتبها غيرنا */
export function isSafeKey(k) {
  return typeof k === 'string' && /^[A-Za-z0-9_-]{1,128}$/.test(k);
}
